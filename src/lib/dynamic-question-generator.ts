/**
 * تولید زنده تست سناریویی جدید به همراه کالبدشکافی تله‌ها
 */
export function generateDynamicLegalQuestion(seedIndex?: number): DynamicQuestion {
  const idx = seedIndex !== undefined ? seedIndex % SCENARIO_TEMPLATES.length : Math.floor(Math.random() * SCENARIO_TEMPLATES.length);
  const tpl = SCENARIO_TEMPLATES[idx];
  
  return {
    id: `dyn_q_${Date.now()}_${idx}`,
    scenario_type: tpl.type,
    story: tpl.story,
    question: tpl.question,
    options: tpl.options,
    correct_index: tpl.correct_index,
    trap_analysis: {
      trap_name: tpl.trap_name,
      deceptive_option: tpl.deceptive_option,
      reason_deceptive: tpl.reason_deceptive
    },
    legal_basis: {
      articles: tpl.articles,
      statute: tpl.statute,
      doctrine: tpl.doctrine
    }
  };
}
